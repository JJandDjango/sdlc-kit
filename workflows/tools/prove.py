"""Prove a drafted test list: red on the repo, green on a prototype, caught by mutations.

usage: prove.py --scratch DIR --test NAME [--mutations FILE] [--timeout SECONDS]

Run from the repository root. The draft sits at DIR/red/NAME. The first run
copies the repo's `taskcontract` package to DIR/proto/ (a later run never
overwrites the drafter's edits there), writes a conftest.py beside the draft
in DIR/red/ and a copy of both in DIR/green/ (whose conftest puts DIR/proto/
first on sys.path), and runs the draft twice: red against the repo, green
against the prototype. FILE is a JSON list of {name, file, old, new}: each
`old` text must match exactly one place in DIR/proto/<file>; the loop applies
it, runs green, records the failing ids, and restores the file byte for byte.

stdout is one compact JSON object:
  ok, scratch, red{summary, red_ok, package, log, passed?, skipped?, not_assertion?, timeout?},
  green{summary, green_ok, package, proto_imported, log, failing?, timeout?},
  mutations: [{name, applied, caught_by, caught_count, log} | {name, applied: false, error}]
             or "skipped: ..." when green is not ok, recovered? (files a dead run left mutated)
A `log` or `package` path inside the scratch folder prints relative to it.
Each run's full pytest output is DIR/logs/<run>.log. A mutation in flight is
journaled in DIR/logs/journal.json (the file's path under proto) and
DIR/logs/orig.bin (its bytes); a run that finds them restores the file first.

exit: 0 red, green and every mutation hold; 1 a check failed; 2 usage;
254 pytest never started.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

PACKAGE = "taskcontract"
SPAWN_FAILED = 254
LINE_CAP = 200
IDS_CAP = 8
NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)

PROBE = '''

# generated by prove.py, rewritten on every run
import sys as _sys
from pathlib import Path as _Path
for _name in [n for n in _sys.modules if n == {pkg!r} or n.startswith({pkg!r} + ".")]:
    del _sys.modules[_name]
{insert}import {pkg} as _pkg
_Path({probe!r}).write_text(_pkg.__file__, encoding="utf-8")
'''


class SpawnFailed(Exception):
    """pytest could not be started at all."""


class Usage(Exception):
    """The command line or a file it names is wrong."""


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def clip(line: str) -> str:
    return line if len(line) <= LINE_CAP else line[:LINE_CAP - 3] + "..."


def under(path: str, scratch: Path) -> str:
    """`path` relative to the scratch folder when it lies inside, else as given."""
    try:
        return Path(path).resolve().relative_to(scratch).as_posix()
    except ValueError:
        return path


def conftest_text(repo: Path, probe: Path, proto: Path | None) -> str:
    """The repo's tests/conftest.py plus the probe that records which package imported."""
    base = repo / "tests" / "conftest.py"
    head = base.read_text(encoding="utf-8") if base.is_file() else ""
    insert = f"_sys.path.insert(0, {str(proto)!r})\n" if proto else ""
    return head + PROBE.format(pkg=PACKAGE, insert=insert, probe=str(probe))


def setup(repo: Path, scratch: Path, test: str, logs: Path) -> tuple[Path, Path]:
    """Create proto/ once, then (re)write both conftests and green's copy of the draft."""
    proto = scratch / "proto"
    if not (proto / PACKAGE).exists():
        shutil.copytree(repo / PACKAGE, proto / PACKAGE,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    red, green = scratch / "red", scratch / "green"
    green.mkdir(exist_ok=True)
    shutil.copyfile(red / test, green / test)
    (red / "conftest.py").write_text(
        conftest_text(repo, logs / "red.package", None), encoding="utf-8")
    (green / "conftest.py").write_text(
        conftest_text(repo, logs / "green.package", proto), encoding="utf-8")
    return red / test, green / test


def kind_of(tag: str, first: str) -> str:
    """assertion, error (setup or collection), or the exception's name."""
    if tag == "error":
        return "error"
    if first.startswith(("assert", "AssertionError", "Failed:")):
        return "assertion"
    return first.split(":", 1)[0].split()[0] if first else "failure"


def read_cases(xml: Path) -> list[dict]:
    cases = []
    for case in ET.parse(xml).getroot().iter("testcase"):
        name, cls = case.get("name", "?"), (case.get("classname") or "").rsplit(".", 1)[-1]
        item = {"id": f"{cls}::{name}" if cls.startswith("Test") else name,
                "outcome": "passed", "kind": "", "line": ""}
        for child in case:
            if child.tag in ("failure", "error"):
                message = (child.get("message") or child.text or "").strip()
                first = message.splitlines()[0] if message else child.tag
                item.update(outcome="failed", kind=kind_of(child.tag, first), line=clip(first))
            elif child.tag == "skipped":
                item["outcome"] = "skipped"
        cases.append(item)
    return cases


def run_pytest(target: Path, label: str, logs: Path, repo: Path, timeout: int) -> dict:
    """Run pytest on `target` from the repo root; return the run's facts."""
    xml, log = logs / f"{label}.xml", logs / f"{label}.log"
    xml.unlink(missing_ok=True)
    env = dict(os.environ, PYTHONUTF8="1", PYTHONDONTWRITEBYTECODE="1")
    cmd = [sys.executable, "-m", "pytest", str(target), "-q", "--tb=short",
           f"--junitxml={xml}", "-p", "no:cacheprovider"]
    facts = {"log": str(log), "cases": [], "timeout": False, "crashed": False}
    try:
        done = subprocess.run(cmd, cwd=repo, env=env, capture_output=True,
                              timeout=timeout, creationflags=NO_WINDOW)
    except subprocess.TimeoutExpired as expired:
        text = ((expired.stdout or b"") + (expired.stderr or b"")).decode("utf-8", "replace")
        log.write_text(text + f"\nTIMEOUT after {timeout}s\n", encoding="utf-8")
        return {**facts, "timeout": True, "summary": f"timeout after {timeout}s"}
    except OSError as err:
        raise SpawnFailed(f"pytest did not start: {err}") from err
    out, err = done.stdout.decode("utf-8", "replace"), done.stderr.decode("utf-8", "replace")
    log.write_text(out + err, encoding="utf-8")
    if "No module named pytest" in out + err:
        raise SpawnFailed("pytest did not start: no module named pytest")
    lines = [line for line in out.splitlines() if line.strip()]
    facts["summary"] = lines[-1].strip("= ").strip() if lines else f"exit {done.returncode}, no output"
    if xml.is_file():
        facts["cases"] = read_cases(xml)
    else:
        facts["crashed"] = True
    return facts


def package_of(logs: Path, label: str) -> str | None:
    probe = logs / f"{label}.package"
    return probe.read_text(encoding="utf-8") if probe.is_file() else None


def prove_red(target: Path, logs: Path, repo: Path, timeout: int) -> dict:
    run = run_pytest(target, "red", logs, repo, timeout)
    cases = run["cases"]
    passed = [c["id"] for c in cases if c["outcome"] == "passed"]
    skipped = [c["id"] for c in cases if c["outcome"] == "skipped"]
    bad = [{"id": c["id"], "kind": c["kind"], "line": c["line"]}
           for c in cases if c["outcome"] == "failed" and c["kind"] != "assertion"]
    ok = bool(cases) and not (passed or skipped or bad or run["timeout"] or run["crashed"])
    out = {"summary": run["summary"], "red_ok": ok, "package": package_of(logs, "red"),
           "log": run["log"]}
    for key, value in (("passed", passed), ("skipped", skipped), ("not_assertion", bad)):
        if value:
            out[key] = value
    if run["timeout"]:
        out["timeout"] = True
    return out


def prove_green(target: Path, logs: Path, repo: Path, proto: Path, timeout: int) -> dict:
    run = run_pytest(target, "green", logs, repo, timeout)
    cases = run["cases"]
    failing = [{"id": c["id"], "line": c["line"]} for c in cases if c["outcome"] != "passed"]
    package = package_of(logs, "green")
    imported = bool(package) and Path(package).resolve().is_relative_to(proto.resolve())
    ok = bool(cases) and not (failing or run["timeout"] or run["crashed"]) and imported
    out = {"summary": run["summary"], "green_ok": ok, "package": package,
           "proto_imported": imported, "log": run["log"]}
    if failing:
        out["failing"] = failing
    if run["timeout"]:
        out["timeout"] = True
    return out


def restore(proto: Path, logs: Path) -> list[str]:
    """Put back a file a dead run left mutated; return the paths restored."""
    journal, orig = logs / "journal.json", logs / "orig.bin"
    if not (journal.is_file() and orig.is_file()):
        return []
    rel = json.loads(journal.read_text(encoding="utf-8"))["file"]
    (proto / rel).write_bytes(orig.read_bytes())
    journal.unlink()
    orig.unlink()
    return [rel]


def mutate(spec: dict, n: int, target: Path, logs: Path, repo: Path, proto: Path,
           timeout: int) -> dict:
    """Apply one mutation to proto, run green, restore; return its record."""
    result = {"name": spec["name"]}
    path = (proto / spec["file"]).resolve()
    if not path.is_relative_to(proto.resolve()) or not path.is_file():
        return {**result, "applied": False, "error": f"{spec['file']} is not a file under proto"}
    original = path.read_bytes()
    text = original.decode("utf-8", "replace")
    matches = text.count(spec["old"])
    if matches != 1:
        return {**result, "applied": False, "error": f"old matches {matches} places, not 1"}
    (logs / "orig.bin").write_bytes(original)
    (logs / "journal.json").write_text(json.dumps({"file": spec["file"]}), encoding="utf-8")
    try:
        path.write_bytes(text.replace(spec["old"], spec["new"], 1).encode("utf-8"))
        run = run_pytest(target, f"mutation-{n}", logs, repo, timeout)
    finally:
        path.write_bytes(original)
        if digest(path.read_bytes()) == digest(original):
            (logs / "journal.json").unlink()
            (logs / "orig.bin").unlink()
    caught = [c["id"] for c in run["cases"] if c["outcome"] != "passed"]
    if run["timeout"]:
        caught = ["(timeout)"]
    out = {**result, "applied": True,
           "caught_by": caught[:IDS_CAP] if caught else "not caught", "log": run["log"]}
    if caught:
        out["caught_count"] = len(caught)
    return out


def load_mutations(path: str | None) -> list[dict]:
    if not path:
        return []
    try:
        items = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as err:
        raise Usage(f"cannot read the mutations file {path}: {err}") from err
    ok = isinstance(items, list) and all(
        isinstance(i, dict) and all(isinstance(i.get(k), str) for k in ("name", "file", "old", "new"))
        and i["old"] for i in items)
    if not ok:
        raise Usage(f"{path} must be a JSON list of {{name, file, old, new}} with a non-empty old")
    return items


def run_all(args: argparse.Namespace) -> tuple[dict, bool]:
    repo, scratch = Path.cwd(), Path(args.scratch).resolve()
    if not (repo / PACKAGE).is_dir():
        raise Usage(f"no {PACKAGE}/ in {repo}: run from the repository root")
    if not (scratch / "red" / args.test).is_file():
        raise Usage(f"no draft at {scratch / 'red' / args.test}")
    specs = load_mutations(args.mutations)
    logs = scratch / "logs"
    logs.mkdir(parents=True, exist_ok=True)
    proto = scratch / "proto"
    recovered = restore(proto, logs) if proto.is_dir() else []
    red_target, green_target = setup(repo, scratch, args.test, logs)
    red = prove_red(red_target, logs, repo, args.timeout)
    green = prove_green(green_target, logs, repo, proto, args.timeout)
    result = {"red": red, "green": green}
    holds = red["red_ok"] and green["green_ok"]
    if specs and not green["green_ok"]:
        result["mutations"] = "skipped: green is not ok"
    elif specs:
        records = [mutate(s, n, green_target, logs, repo, proto, args.timeout)
                   for n, s in enumerate(specs, 1)]
        result["mutations"] = records
        holds = holds and all(r["applied"] and r["caught_by"] != "not caught" for r in records)
    if recovered:
        result["recovered"] = recovered
    for record in (red, green, *(result["mutations"] if isinstance(result.get("mutations"), list) else [])):
        for key in ("log", "package"):
            if record.get(key):
                record[key] = under(record[key], scratch)
    return {"ok": holds, "scratch": str(scratch), **result}, holds


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="prove.py", description="Prove a drafted test list.")
    parser.add_argument("--scratch", required=True, help="the drafter's scratch folder")
    parser.add_argument("--test", required=True, help="the draft's file name under SCRATCH/red")
    parser.add_argument("--mutations", help="JSON list of {name, file, old, new}")
    parser.add_argument("--timeout", type=int, default=600, help="seconds a pytest run may take")
    args = parser.parse_args(argv)
    try:
        result, holds = run_all(args)
    except Usage as err:
        print(f"prove.py: {err}", file=sys.stderr)
        return 2
    except SpawnFailed as err:
        print(f"prove.py: {err}", file=sys.stderr)
        return SPAWN_FAILED
    print(json.dumps(result, separators=(",", ":"), ensure_ascii=False))
    return 0 if holds else 1


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
